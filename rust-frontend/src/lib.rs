//! Palet Vendéen Frontend - Dioxus Implementation
//!
//! Library crate for the frontend application

pub mod components;
pub mod hooks;
pub mod pages;
pub mod services;
pub mod utils;

use dioxus::prelude::*;
use log::info;
use wasm_bindgen::prelude::wasm_bindgen;

use hooks::use_auth::provide_auth;
use pages::{
    actualite_detail::ActualiteDetail, actualites::Actualites, arbitrage::Arbitrage,
    arbitrage_match::ArbitrageMatch, championship_detail::ChampionnatDetail,
    championships::Championnats, club_detail::ClubDetail, clubs::Clubs, compte::MonCompte,
    connexion::Connexion, federation::Federation, home::Home, inscription::Inscription,
    mon_club::MonClub, not_found::NotFound, player_detail::PlayerDetail, players::Joueurs,
    tournament_detail::TournamentDetail, tournaments::Tournois,
};

/// Route definitions
#[derive(Clone, Debug, PartialEq, Routable)]
#[rustfmt::skip]
enum Route {
    #[route("/")]
    Home,
    #[route("/championnats")]
    Championnats,
    #[route("/championnats/:id")]
    ChampionnatDetail { id: String },
    #[route("/tournois")]
    Tournois,
    #[route("/tournois/:id")]
    TournamentDetail { id: String },
    #[route("/clubs")]
    Clubs,
    #[route("/clubs/:id")]
    ClubDetail { id: String },
    #[route("/joueurs")]
    Joueurs,
    #[route("/joueurs/:id")]
    PlayerDetail { id: String },
    #[route("/actualites")]
    Actualites,
    #[route("/actualites/:id")]
    ActualiteDetail { id: String },
    #[route("/mon-compte")]
    MonCompte,
    #[route("/mon-club")]
    MonClub,
    #[route("/arbitrage")]
    Arbitrage,
    #[route("/arbitrage/:id")]
    ArbitrageMatch { id: String },
    #[route("/federation")]
    Federation,
    #[route("/connexion")]
    Connexion,
    #[route("/inscription")]
    Inscription,
    #[route("/404")]
    NotFound,
}

/// Main App component
#[component]
fn App() -> Element {
    provide_auth();
    rsx! {
        Router::<Route> {}
    }
}

/// WASM entry point, executed automatically when the module is instantiated
/// by the JS glue generated by wasm-pack.
#[wasm_bindgen(start)]
pub fn start() {
    // Initialize logging
    wasm_logger::init(wasm_logger::Config::default());

    info!("Starting Palet Vendéen Frontend with Dioxus...");

    // Launch the app
    launch(App);
}
